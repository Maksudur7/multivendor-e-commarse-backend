// issueTokens creates a session, generates JWT tokens, and sets cookies.
func (h *Handler) issueTokens(c *fiber.Ctx, user interface{ GetID() uuid.UUID; GetRole() string }) error {
	sessionID := uuid.New()

	// Generate tokens
	accessToken, err := middleware.GenerateAccessToken(
		user.GetID().String(), user.GetRole(), sessionID.String(),
		h.cfg.JWT.AccessSecret, h.cfg.JWT.AccessExpiry,
	)
	if err != nil {
		return response.InternalError(c)
	}

	refreshToken := generateSecureToken()
	tokenHash := hashToken(refreshToken)
	refreshExpiry := time.Now().Add(h.cfg.JWT.RefreshExpiry)

	// Create session in DB
	h.store.CreateSession(context.Background(), CreateSessionParams{
		UserID:           user.GetID(),
		ID:               sessionID,
		RefreshTokenHash: tokenHash,
		IPAddress:        c.IP(),
		UserAgent:        c.Get("User-Agent"),
		ExpiresAt:        refreshExpiry,
	})

	// Set HTTP-only cookie for refresh token
	setRefreshTokenCookie(c, refreshToken, refreshExpiry)

	return response.OK(c, TokenResponse{
		AccessToken: accessToken,
		ExpiresIn:   int64(h.cfg.JWT.AccessExpiry.Seconds()),
		TokenType:   "Bearer",
	})
}

func setRefreshTokenCookie(c *fiber.Ctx, token string, expiry time.Time) {
	c.Cookie(&fiber.Cookie{
		Name:     "refresh_token",
		Value:    token,
		Expires:  expiry,
		HTTPOnly: true,
		Secure:   true,
		SameSite: "Strict",
		Path:     "/api/v1/auth/refresh",
	})
}

func generateOTP() (string, error) {
	max := big.NewInt(1000000)
	n, err := rand.Int(rand.Reader, max)
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("%06d", n.Int64()), nil
}

func generateSecureToken() string {
	b := make([]byte, 32)
	rand.Read(b)
	return hex.EncodeToString(b)
}

func generateReferralCode() string {
	b := make([]byte, 4)
	rand.Read(b)
	return strings.ToUpper(hex.EncodeToString(b))
}

func hashToken(token string) string {
	// Simple SHA-256 hash for storage
	// In production use crypto/sha256
	return fmt.Sprintf("%x", token)
}

func isValidBDPhone(phone string) bool {
	re := regexp.MustCompile(`^(?:\+88)?01[3-9]\d{8}$`)
	return re.MatchString(phone)
}

func normalizePhone(phone string) string {
	phone = strings.TrimPrefix(phone, "+88")
	phone = strings.TrimPrefix(phone, "88")
	return phone
}

func maskPhone(phone string) string {
	if len(phone) < 7 {
		return phone
	}
	return phone[:3] + "****" + phone[len(phone)-3:]
}

